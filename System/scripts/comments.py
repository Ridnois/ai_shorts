#!/usr/bin/env python3
"""Comments on Next Token videos: read them, draft replies, post only what the user approved (Strategy §Comments).
  python3 System/scripts/comments.py pull      # every thread on the channel -> Analytics/comments.csv + Analytics/Comments.md (GENERATED)
  python3 System/scripts/comments.py draft     # unanswered threads -> Analytics/replies.json (the agent fills "reply")
  python3 System/scripts/comments.py check     # replies.json against the rules: length, banned words, links, no "!"
  python3 System/scripts/comments.py post      # posts entries with "approved": true and a reply; logs each comment id
Needs the youtube.force-ssl scope (youtube_auth.py, since 3 Nov 2026). Run from the vault root. Posting is outward-facing:
the agent shows the user every reply, word for word, and sets "approved" only on the user's yes. Liking (a heart) and
pinning are Studio only; no API does them."""
import csv, datetime as dt, json, os, re, sys, urllib.error, urllib.request
sys.path.insert(0, os.path.dirname(__file__))
import youtube_auth as ya

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CSV, MD, RJ = (os.path.join(ROOT, "Analytics", f) for f in ("comments.csv", "Comments.md", "replies.json"))
API = "https://www.googleapis.com/youtube/v3/"
FIELDS = ["thread_id", "comment_id", "video_id", "video", "author", "published", "likes", "text", "replies", "answered", "kind"]
BANNED = ["did you know", "game-changing", "revolutionary", "mind-blowing", "insane", "unlock", "supercharge", "journey",
          "this changes everything", "like and subscribe", "seamless", "superpowers", "the future of", "great question"]
SPAM = re.compile(r"(https?://|t\.me/|whatsapp|telegram|crypto|forex|\bdm me\b|check my (channel|profile)|promo|sub4sub)", re.I)


def names():
    """youtube_id -> our video name (Analytics/videos.csv)."""
    p = os.path.join(ROOT, "Analytics", "videos.csv")
    return {r["youtube_id"]: r["video"] for r in csv.DictReader(open(p, encoding="utf-8")) if r["youtube_id"]} if os.path.exists(p) else {}


def kind(text):
    t = text.strip()
    if SPAM.search(t): return "spam"
    if "?" in t or re.match(r"(?i)(how|why|what|when|where|which|who|can|does|is|are|do|will|would|should)\b", t): return "question"
    if re.search(r"(?i)\b(wrong|incorrect|not true|false|actually|mistake|misleading)\b", t): return "correction"
    return "remark"


def pull(_):
    tok = ya.access_token(); rows, page = [], None; vn = names()
    while True:
        q = dict(part="snippet,replies", allThreadsRelatedToChannelId=ya.CHANNEL_ID, maxResults=100, order="time", textFormat="plainText")
        if page: q["pageToken"] = page
        r = ya.get(API + "commentThreads", tok, **q)
        for it in r.get("items", []):
            s = it["snippet"]; c = s["topLevelComment"]["snippet"]
            ours = any(x["snippet"].get("authorChannelId", {}).get("value") == ya.CHANNEL_ID for x in it.get("replies", {}).get("comments", []))
            mine = c.get("authorChannelId", {}).get("value") == ya.CHANNEL_ID
            rows.append(dict(thread_id=it["id"], comment_id=s["topLevelComment"]["id"], video_id=s.get("videoId", ""),
                             video=vn.get(s.get("videoId", ""), s.get("videoId", "")), author=c["authorDisplayName"],
                             published=c["publishedAt"][:16].replace("T", " "), likes=c.get("likeCount", 0),
                             text=c["textDisplay"].replace("\n", " ").strip(), replies=s.get("totalReplyCount", 0),
                             answered="ours" if mine else ("yes" if ours else "no"), kind="ours" if mine else kind(c["textDisplay"])))
        page = r.get("nextPageToken")
        if not page: break
    with open(CSV, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS); w.writeheader(); w.writerows(rows)
    report(rows)
    todo = [r for r in rows if r["answered"] == "no" and r["kind"] != "spam"]
    print(f"COMMENTS {len(rows)} threads, {len(todo)} unanswered (not spam) -> Analytics/comments.csv, Analytics/Comments.md")


def report(rows):
    today = dt.date.today()
    L = ["---", "type: research", f"updated: {today}", "status: GENERATED by System/scripts/comments.py pull; do not edit by hand", "---", "",
         "# Comments", "", "← [[Strategy]] §Comments (how we answer) · [[Report]] · data: `Analytics/comments.csv`", "",
         f"{len(rows)} threads. **Questions** are idea leads: a question asked twice becomes an idea note ([[Strategy]] §Ideas).", ""]
    for head, cond in (("Unanswered", lambda r: r["answered"] == "no" and r["kind"] != "spam"),
                       ("Spam or links (never answered; hide in Studio)", lambda r: r["kind"] == "spam"),
                       ("Answered", lambda r: r["answered"] in ("yes", "ours") and r["kind"] != "ours")):
        g = [r for r in rows if cond(r)]
        L += [f"## {head} ({len(g)})", "", "| video | when | who | kind | comment | likes |", "| --- | --- | --- | --- | --- | --- |"]
        for r in g:
            L.append(f"| {r['video']} | {r['published']} | {r['author'].replace('|', '/')} | {r['kind']} | {r['text'][:160].replace('|', '/')} | {r['likes']} |")
        L.append("")
    qs = [r for r in rows if r["kind"] == "question"]
    if qs:
        L += ["## Questions viewers asked (idea leads)", ""] + [f"- {r['text'][:200]} ({r['video']})" for r in qs] + [""]
    open(MD, "w", encoding="utf-8").write("\n".join(L) + "\n")


def draft(_):
    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    old = {e["thread_id"]: e for e in (json.load(open(RJ)) if os.path.exists(RJ) else [])}
    out = []
    for r in rows:
        if r["answered"] != "no" or r["kind"] == "spam": continue
        e = old.get(r["thread_id"], {"reply": "", "approved": False, "posted": ""})
        e.update({k: r[k] for k in ("thread_id", "comment_id", "video", "author", "kind", "text")})
        out.append(e)
    out += [e for t, e in old.items() if e.get("posted") and t not in {x["thread_id"] for x in out}]   # keep the log of posted ones
    json.dump(out, open(RJ, "w"), indent=1, ensure_ascii=False)
    print(f"DRAFT {sum(1 for e in out if not e.get('posted'))} to answer -> Analytics/replies.json (fill \"reply\"; \"approved\" only on the user's yes)")


def problems(e):
    t, p = e.get("reply", ""), []
    if not t.strip(): return ["empty"]
    if len(t) > 400: p.append(f"{len(t)} characters (400 or fewer)")
    if "!" in t: p.append("exclamation mark")
    if re.search(r"https?://", t): p.append("a link (sources go in the description, not in replies)")
    p += [f"banned phrase '{b}'" for b in BANNED if b in t.lower()]
    if re.search(r"@\w", t): p.append("an @mention (YouTube tags the parent author already)")
    return p


def check(_):
    es = json.load(open(RJ)); bad = 0
    for e in es:
        if e.get("posted"): continue
        pr = problems(e)
        print(f"{'OK  ' if not pr else 'FIX '} {e['video']} · {e['author']}: {e.get('reply', '')[:90]!r}" + (f"  <- {'; '.join(pr)}" if pr else ""))
        bad += bool(pr)
    print(f"CHECK {'PASS' if not bad else 'FAIL'}: {bad} to fix")
    return bad


def post(_):
    if check(None): sys.exit("fix the replies first")
    es = json.load(open(RJ)); tok = ya.access_token(); n = 0
    for e in es:
        if e.get("posted") or not e.get("approved") or not e.get("reply", "").strip(): continue
        body = json.dumps({"snippet": {"parentId": e["comment_id"], "textOriginal": e["reply"]}}).encode()
        req = urllib.request.Request(API + "comments?part=snippet", body, headers={"Authorization": "Bearer " + tok, "Content-Type": "application/json"})
        try:
            r = json.load(urllib.request.urlopen(req))
        except urllib.error.HTTPError as x:
            sys.exit(f"HTTP {x.code} on {e['author']}: {x.read().decode()[:300]} (403 insufficient scopes: run youtube_auth.py)")
        e["posted"] = f"{r['id']} {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M}Z"; n += 1
        json.dump(es, open(RJ, "w"), indent=1, ensure_ascii=False)
        print(f"posted to {e['author']} on {e['video']}: {r['id']}")
    print(f"POST {n} replies")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    fn = {"pull": pull, "draft": draft, "check": check, "post": post}.get(cmd)
    if not fn: sys.exit(__doc__)
    try: fn(sys.argv[2:])
    except urllib.error.HTTPError as x:
        sys.exit(f"HTTP {x.code}: {x.read().decode()[:300]} (403 insufficient scopes: run python3 System/scripts/youtube_auth.py once)")
